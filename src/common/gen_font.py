"""Generate font_dm.h: anti-aliased glyph alpha maps for the status bar.
Small: ASCII 0x20-0x7E, 8x16 cells (DejaVu Sans Mono Bold).
Big:   '0'-'9' and ':' at 24x40 cells (DejaVu Sans Mono Bold).
DejaVu fonts are under the Bitstream Vera / DejaVu license, which allows embedding."""
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"


def glyphs(chars, cw, ch, px, yoff):
    f = ImageFont.truetype(FONT, px)
    out = []
    for c in chars:
        im = Image.new("L", (cw, ch), 0)
        d = ImageDraw.Draw(im)
        w = d.textlength(c, font=f)
        d.text(((cw - w) / 2, yoff), c, font=f, fill=255)
        out.append(list(im.getdata()))
    return out


def emit(name, data, cw, ch):
    lines = [f"static const unsigned char {name}[{len(data)}][{cw * ch}] = {{"]
    for g in data:
        lines.append("  {" + ",".join(str(v) for v in g) + "},")
    lines.append("};")
    return "\n".join(lines)


small = glyphs([chr(c) for c in range(0x20, 0x7F)], 8, 16, 13, 0)
big = glyphs(list("0123456789:"), 24, 40, 38, -3)
with open("font_dm.h", "w") as fh:
    fh.write("/* Generated by gen_font.py - do not edit. */\n#pragma once\n")
    fh.write("#define DM_SMALL_W 8\n#define DM_SMALL_H 16\n#define DM_BIG_W 24\n#define DM_BIG_H 40\n")
    fh.write(emit("dm_small", small, 8, 16) + "\n")
    fh.write(emit("dm_big", big, 24, 40) + "\n")
print("ok")
